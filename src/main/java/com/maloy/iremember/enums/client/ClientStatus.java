package com.maloy.iremember.enums.client;

public enum ClientStatus {
    NEW,
    LEAD,           // потенциальный клиент, ещё не подтверждён
    NEGOTIATION,    // идут переговоры/обсуждение условий
    ACTIVE,         // активный клиент, работа ведётся
    ON_HOLD,        // временная пауза (например, ждём оплату/решение)
    COMPLETED,      // проект/сотрудничество завершено успешно
    CANCELLED,      // отменено (клиент отказался или сорвалась сделка)
    ARCHIVED        // архивный клиент — старое сотрудничество, не активен
}
